export type IsoCountryCode = (typeof ISO_COUNTRY_CODES)[number]

export type CountryOption = {
  code: IsoCountryCode
  /** Localized display name for the active locale. */
  name: string
  /** Stable English name used when matching legacy free-text profiles. */
  enName: string
}

const enDisplayNames =
  typeof Intl !== "undefined"
    ? new Intl.DisplayNames(["en"], { type: "region" })
    : null

function englishCountryName(code: string) {
  return enDisplayNames?.of(code) ?? code
}

/** Localized, alphabetically sorted country options for a UI locale. */
export function getCountryOptions(locale: string): CountryOption[] {
  const display = new Intl.DisplayNames([locale, "en"], { type: "region" })
  return ISO_COUNTRY_CODES.map((code) => ({
    code,
    name: display.of(code) ?? englishCountryName(code),
    enName: englishCountryName(code),
  })).sort((a, b) => a.name.localeCompare(b.name, locale))
}

/**
 * Resolve a stored profile country (English name, localized name, or ISO code)
 * back to an ISO code when possible.
 */
export function matchCountryCode(
  stored: string,
  options: CountryOption[]
): IsoCountryCode | "" {
  const value = stored.trim()
  if (!value) return ""
  const upper = value.toUpperCase()
  if (options.some((option) => option.code === upper)) {
    return upper as IsoCountryCode
  }
  const byEn = options.find(
    (option) => option.enName.toLowerCase() === value.toLowerCase()
  )
  if (byEn) return byEn.code
  const byName = options.find(
    (option) => option.name.toLowerCase() === value.toLowerCase()
  )
  return byName?.code ?? ""
}
